"""Home page: FAQ JSON-LD for both languages, and /en/index.html.

index.html is hand-written in Arabic and carries every visible string twice,
as data-ar/data-en on leaf elements. This script:

  1. regenerates the FAQPage JSON-LD in index.html (between the faq-jsonld
     markers) from the visible FAQ, so the rich result always matches the page;
  2. writes /en/index.html: the same page with the English strings, English
     head tags, lang="en" dir="ltr", English links and its own FAQ JSON-LD.

build_site.py calls main() after it has patched the library band, so the
English page always carries the current band. It can also be run on its own.
"""
import json
import os

from bs4 import BeautifulSoup
from bs4.formatter import HTMLFormatter


class _KeepOrder(HTMLFormatter):
    # The default formatter sorts attributes alphabetically, which turns
    # <meta name=.. content=..> into <meta content=.. name=..> and breaks the
    # regex checks in seo_audit.py. Keep the source order instead.
    def attributes(self, tag):
        return list(tag.attrs.items())


KEEP = _KeepOrder(void_element_close_prefix=None)

BASE = os.path.dirname(os.path.abspath(__file__))
HOME = os.path.join(BASE, "index.html")
EN_HOME = os.path.join(BASE, "en", "index.html")
SITE = "https://www.sihtak.com"

FAQ_START = "<!-- faq-jsonld:start (generated by build_home.py) -->"
FAQ_END = "<!-- faq-jsonld:end -->"

# English head. Title about 60 characters, description about 160: what Google
# actually shows in the result list.
EN = {
    "title": "Sihtak: Free Medicine Reminders and Lab Results Explained",
    "description": ("Free health app in Arabic and English: a reminder for every dose, lab "
                    "results explained from a photo, a health assistant and family profiles."),
    "og:title": "Sihtak: your medicine on time, your lab results explained",
    "og:description": ("A free health app in Arabic and English: a reminder for every dose, "
                       "plain-language lab results, a health assistant and your family's "
                       "health in one place."),
    "og:image:alt": "The Sihtak app: medicine reminders and lab results explained",
    "og:locale": "en_US",
    "og:locale:alternate": "ar_AR",
}


def faq_jsonld(soup, lang):
    """FAQPage JSON-LD built from the visible FAQ items in `lang`."""
    items = []
    for item in soup.select("#faq .faq-item"):
        q = item.select_one(".faq-q [data-ar]")
        a = item.select_one(".faq-a [data-ar]")
        if not q or not a:
            continue
        items.append({
            "@type": "Question",
            "name": q[f"data-{lang}"],
            "acceptedAnswer": {"@type": "Answer", "text": a[f"data-{lang}"]},
        })
    if not items:
        raise SystemExit("index.html: no FAQ items found under #faq")
    data = {"@context": "https://schema.org", "@type": "FAQPage",
            "inLanguage": lang, "mainEntity": items}
    body = json.dumps(data, ensure_ascii=False, indent=2)
    return '<script type="application/ld+json">\n' + body + "\n  </script>"


def splice(page, block):
    i, j = page.find(FAQ_START), page.find(FAQ_END)
    if i < 0 or j < 0 or j < i:
        raise SystemExit("index.html has lost its faq-jsonld markers")
    return page[:i] + FAQ_START + "\n  " + block + "\n  " + page[j:]


def english(page):
    soup = BeautifulSoup(page, "html.parser")
    html = soup.html
    html["lang"] = "en"
    html["dir"] = "ltr"

    soup.title.string = EN["title"]

    def meta(attr, key, value):
        tag = soup.find("meta", attrs={attr: key})
        if tag is not None:
            tag["content"] = value

    meta("name", "description", EN["description"])
    meta("property", "og:title", EN["og:title"])
    meta("property", "og:description", EN["og:description"])
    meta("property", "og:image:alt", EN["og:image:alt"])
    meta("property", "og:locale", EN["og:locale"])
    meta("property", "og:locale:alternate", EN["og:locale:alternate"])
    meta("property", "og:url", SITE + "/en/")
    meta("name", "twitter:title", EN["og:title"])
    meta("name", "twitter:description", EN["og:description"])
    soup.find("link", rel="canonical")["href"] = SITE + "/en/"

    for el in soup.select("[data-ar][data-en]"):
        el.string = el["data-en"]
    for el in soup.select("[data-href-en]"):
        el["href"] = el["data-href-en"]

    lang = soup.select_one("a.lang-btn")
    lang["href"] = "/"
    lang["hreflang"] = "ar"
    lang["lang"] = "ar"
    lang.string = "عربي"

    out = soup.decode(formatter=KEEP)
    return splice(out, faq_jsonld(soup, "en"))


def main():
    with open(HOME, encoding="utf-8") as fh:
        page = fh.read()
    soup = BeautifulSoup(page, "html.parser")
    new = splice(page, faq_jsonld(soup, "ar"))
    changed = new != page
    if changed:
        with open(HOME, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(new)
    os.makedirs(os.path.dirname(EN_HOME), exist_ok=True)
    with open(EN_HOME, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(english(new))
    print("  home: FAQ JSON-LD " + ("rewritten" if changed else "already current")
          + ", /en/index.html written")


if __name__ == "__main__":
    main()
